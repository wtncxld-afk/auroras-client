const { contextBridge, ipcRenderer: ir } = require("electron");
contextBridge.exposeInMainWorld("auroras", {
  desktop: true,
  http: (o) => ir.invoke("http", o),
  installMod: (o) => ir.invoke("install", o),
  removeMod: (o) => ir.invoke("remove", o),
  installed: (id) => ir.invoke("installed", id),
  deps: (o) => ir.invoke("deps", o),
  settings: () => ir.invoke("settings"),
  setCfKey: (k) => ir.invoke("setCfKey", k),
  saveFile: (o) => ir.invoke("save", o),
  open: (u) => ir.invoke("open", u),
  win: (a) => ir.send("win", a),
  skinLookup: (n) => ir.invoke("skin:lookup", { name: n }),
  skinRefresh: (id) => ir.invoke("skin:refresh", id),
  skinUpload: (o) => ir.invoke("skin:upload", o),
  authStart: () => ir.invoke("auth:start"),
  authWindow: () => ir.invoke("auth:window"),
  releaseCheck: () => ir.invoke("release:check"),
  updateAuto: (on) => ir.invoke("update:auto", !!on), updateInstall: () => ir.invoke("update:install"),
  onUpdateReady: (fn) => { ir.removeAllListeners("update:ready"); ir.on("update:ready", (_e, d) => fn(d)); },
  modStatus: (id) => ir.invoke("mod:status", id),
  authCancel: () => ir.invoke("auth:cancel"),
  onAuthDone: (f) => ir.on("auth:done", (_e, d) => f(d)),
  removeAccount: (id) => ir.invoke("accounts:remove", id),
  accountsStatus: () => ir.invoke("accounts:status"),
  serverStatus: (addr) => ir.invoke("server:status", addr),
  settingsAll: () => ir.invoke("settings:all"),
  setSettings: (o) => ir.invoke("settings:set", o),
  updateCheck: (o) => ir.invoke("update:check", o),
  updateInstallClient: (o) => ir.invoke("update:installClient", o),
  versions: (o) => ir.invoke("versions:list", o),
  versionMeta: (id) => ir.invoke("versions:meta", id),
  instancePrepare: (o) => ir.invoke("instance:prepare", o),
  launch: (o) => ir.invoke("launch", o),
  onLaunch: (f) => ir.on("launch:state", (_e, d) => f(d)),
  modcfgRead: (id) => ir.invoke("modcfg:read", id),
  modcfgUpdate: (o) => ir.invoke("modcfg:update", o),
  modcfgAssign: (o) => ir.invoke("modcfg:assign", o),
  vanillaTexture: (o) => ir.invoke("vanilla:texture", o),
  spotifyConnect: () => ir.invoke("spotify:connect"),
  spotifyDisconnect: () => ir.invoke("spotify:disconnect"),
  layoutsList: (id) => ir.invoke("layouts:list", id),
  layoutsSave: (o) => ir.invoke("layouts:save", o),
  layoutsDelete: (o) => ir.invoke("layouts:delete", o),
  emotesList: (id) => ir.invoke("emotes:list", id),
  emotesSave: (o) => ir.invoke("emotes:save", o),
  emotesDelete: (o) => ir.invoke("emotes:delete", o),
  emotesWheel: (o) => ir.invoke("emotes:wheel", o),
  capeWrite: (o) => ir.invoke("cape:write", o),
  capeClear: (id) => ir.invoke("cape:clear", id),
  capeLibList: () => ir.invoke("capelib:list"),
  friendsState: () => ir.invoke("friends:state"),
  friendsOverview: (uuid) => ir.invoke("friends:overview", uuid),
  friendsAct: (o) => ir.invoke("friends:act", o),
  friendsPresence: (o) => ir.invoke("friends:presence", o),
  capeLibSave: (d) => ir.invoke("capelib:save", d),
  capeLibRename: (d) => ir.invoke("capelib:rename", d),
  capeLibDelete: (id) => ir.invoke("capelib:delete", id),
  onProgress: (f) => ir.on("progress", (_e, d) => f(d)),
});
