import { ApiError } from "../http";
/** Path ids are UUIDs; anything else is rejected before it reaches a query. */
export function uuidParam(v: string): string {
  if (!/^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(v))) throw new ApiError(404, "not_found", "Not found.");
  return v.toLowerCase();
}
export const isUuid = (v: string) => /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i.test(String(v));
